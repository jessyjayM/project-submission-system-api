-- =====================================================================
-- ISCTEM - Sistema de Gestao de Workflow de TCC
-- V1: esquema inicial (seccao 5.3 do levantamento de requisitos)
-- =====================================================================

-- ---------------------------------------------------------------------
-- Utilizadores (RF01, RF02, RF03)
-- ---------------------------------------------------------------------
CREATE TABLE utilizador (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(150)  NOT NULL,
    tipo                VARCHAR(20)   NOT NULL,
    email               VARCHAR(150),
    codigo              VARCHAR(50),
    senha_hash          VARCHAR(100)  NOT NULL,
    estado              VARCHAR(20)   NOT NULL DEFAULT 'ACTIVO',
    deve_alterar_senha  BOOLEAN       NOT NULL DEFAULT TRUE,
    tentativas_falhadas INTEGER       NOT NULL DEFAULT 0,
    bloqueado_ate       TIMESTAMPTZ,
    ultimo_acesso       TIMESTAMPTZ,
    criado_em           TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    actualizado_em      TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_utilizador_tipo   CHECK (tipo IN ('ADMIN', 'COORDENADOR', 'DOCENTE', 'ESTUDANTE')),
    CONSTRAINT ck_utilizador_estado CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    -- RF02: estudante autentica-se pelo codigo, docente/coordenador pelo email institucional
    CONSTRAINT ck_utilizador_credencial CHECK (
        (tipo = 'ESTUDANTE' AND codigo IS NOT NULL)
        OR (tipo <> 'ESTUDANTE' AND email IS NOT NULL)
    )
);
CREATE UNIQUE INDEX ux_utilizador_email  ON utilizador (LOWER(email))  WHERE email IS NOT NULL;
CREATE UNIQUE INDEX ux_utilizador_codigo ON utilizador (LOWER(codigo)) WHERE codigo IS NOT NULL;

-- ---------------------------------------------------------------------
-- Docente / Supervisor
-- ---------------------------------------------------------------------
CREATE TABLE docente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilizador_id  BIGINT       NOT NULL UNIQUE REFERENCES utilizador (id) ON DELETE CASCADE,
    departamento   VARCHAR(120) NOT NULL,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actualizado_em TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- Estudante (RF04: um supervisor activo de cada vez)
-- ---------------------------------------------------------------------
CREATE TABLE estudante (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilizador_id   BIGINT       NOT NULL UNIQUE REFERENCES utilizador (id) ON DELETE CASCADE,
    curso           VARCHAR(120) NOT NULL,
    area            VARCHAR(20)  NOT NULL,
    supervisor_id   BIGINT       REFERENCES docente (id) ON DELETE SET NULL,
    estado_processo VARCHAR(30)  NOT NULL DEFAULT 'SEM_SUPERVISOR',
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_estudante_area CHECK (area IN ('INFORMATICA', 'OUTRA')),
    CONSTRAINT ck_estudante_estado CHECK (estado_processo IN
        ('SEM_SUPERVISOR', 'EM_CURSO', 'APTO_PARA_DEFESA', 'CONCLUIDO'))
);
CREATE INDEX ix_estudante_supervisor ON estudante (supervisor_id);

-- Historico de atribuicoes de supervisor (RF04 + RNF04)
CREATE TABLE atribuicao_supervisor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudante_id   BIGINT      NOT NULL REFERENCES estudante (id) ON DELETE CASCADE,
    docente_id     BIGINT      NOT NULL REFERENCES docente (id) ON DELETE CASCADE,
    atribuido_por  BIGINT      NOT NULL REFERENCES utilizador (id),
    inicio         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fim            TIMESTAMPTZ,
    motivo         VARCHAR(500)
);
CREATE INDEX ix_atribuicao_estudante ON atribuicao_supervisor (estudante_id);
-- Regra de negocio: cada estudante so pode ter uma atribuicao activa (fim IS NULL)
CREATE UNIQUE INDEX ux_atribuicao_activa ON atribuicao_supervisor (estudante_id) WHERE fim IS NULL;

-- ---------------------------------------------------------------------
-- TCC (RF05)
-- ---------------------------------------------------------------------
CREATE TABLE tcc (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudante_id      BIGINT       NOT NULL UNIQUE REFERENCES estudante (id) ON DELETE CASCADE,
    titulo            VARCHAR(300),
    curso             VARCHAR(120) NOT NULL,
    area              VARCHAR(20)  NOT NULL,
    data_inicio       DATE         NOT NULL DEFAULT CURRENT_DATE,
    data_fim_prevista DATE,
    fase_actual       INTEGER      NOT NULL DEFAULT 1,
    estado_geral      VARCHAR(30)  NOT NULL DEFAULT 'EM_CURSO',
    criado_em         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_tcc_area  CHECK (area IN ('INFORMATICA', 'OUTRA')),
    CONSTRAINT ck_tcc_fase  CHECK (fase_actual BETWEEN 1 AND 5),
    CONSTRAINT ck_tcc_estado CHECK (estado_geral IN ('EM_CURSO', 'APTO_PARA_DEFESA', 'CONCLUIDO', 'CANCELADO'))
);

-- ---------------------------------------------------------------------
-- Fases do workflow (seccao 5.4 - maquina de estados)
-- em_atraso e um estado transversal: acumula com o estado do fluxo,
-- nunca o substitui (ex.: "EM_REVISAO - Em Atraso").
-- ---------------------------------------------------------------------
CREATE TABLE fase (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tcc_id         BIGINT       NOT NULL REFERENCES tcc (id) ON DELETE CASCADE,
    numero         INTEGER      NOT NULL,
    nome           VARCHAR(120) NOT NULL,
    estado         VARCHAR(30)  NOT NULL DEFAULT 'PENDENTE',
    em_atraso      BOOLEAN      NOT NULL DEFAULT FALSE,
    data_inicio    DATE,
    data_limite    DATE,
    data_aprovacao TIMESTAMPTZ,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actualizado_em TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_fase_numero CHECK (numero BETWEEN 1 AND 5),
    CONSTRAINT ck_fase_estado CHECK (estado IN ('PENDENTE', 'EM_REVISAO', 'CORRECAO_SOLICITADA', 'APROVADO')),
    CONSTRAINT ux_fase_tcc_numero UNIQUE (tcc_id, numero)
);
CREATE INDEX ix_fase_limite ON fase (data_limite) WHERE estado <> 'APROVADO';

-- ---------------------------------------------------------------------
-- Submissoes (RF05, RF06)
-- ---------------------------------------------------------------------
CREATE TABLE submissao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fase_id              BIGINT      NOT NULL REFERENCES fase (id) ON DELETE CASCADE,
    autor_id             BIGINT      NOT NULL REFERENCES utilizador (id),
    numero               INTEGER     NOT NULL,
    comentario_estudante VARCHAR(2000),
    estado               VARCHAR(30) NOT NULL DEFAULT 'EM_REVISAO',
    data_submissao       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_decisao         TIMESTAMPTZ,
    criado_em            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_em       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_submissao_estado CHECK (estado IN ('EM_REVISAO', 'CORRECAO_SOLICITADA', 'APROVADO')),
    CONSTRAINT ux_submissao_fase_numero UNIQUE (fase_id, numero)
);
CREATE INDEX ix_submissao_fase ON submissao (fase_id);

-- Decisao do supervisor sobre uma submissao (alimenta o tempo medio de resposta - RF11)
CREATE TABLE revisao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submissao_id  BIGINT      NOT NULL REFERENCES submissao (id) ON DELETE CASCADE,
    revisor_id    BIGINT      NOT NULL REFERENCES utilizador (id),
    decisao       VARCHAR(30) NOT NULL,
    comentario    VARCHAR(4000),
    data_revisao  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_revisao_decisao CHECK (decisao IN ('APROVADO', 'CORRECAO_SOLICITADA'))
);
CREATE INDEX ix_revisao_submissao ON revisao (submissao_id);

-- ---------------------------------------------------------------------
-- Versoes de documento (RF06: a versao anterior nunca e substituida)
-- ---------------------------------------------------------------------
CREATE TABLE versao_documento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submissao_id   BIGINT       NOT NULL REFERENCES submissao (id) ON DELETE CASCADE,
    numero_versao  INTEGER      NOT NULL,
    nome_original  VARCHAR(255) NOT NULL,
    caminho        VARCHAR(500) NOT NULL,
    tipo_conteudo  VARCHAR(120) NOT NULL,
    extensao       VARCHAR(10)  NOT NULL,
    tamanho_bytes  BIGINT       NOT NULL,
    hash_sha256    VARCHAR(64)  NOT NULL,
    texto_extraido TEXT,
    data_upload    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_versao_extensao CHECK (extensao IN ('pdf', 'doc', 'docx')),
    CONSTRAINT ux_versao_submissao UNIQUE (submissao_id, numero_versao)
);
CREATE INDEX ix_versao_submissao ON versao_documento (submissao_id);

-- ---------------------------------------------------------------------
-- Relatorios de plagio (RF08)
-- ---------------------------------------------------------------------
CREATE TABLE relatorio_plagio (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao_documento_id      BIGINT        NOT NULL UNIQUE REFERENCES versao_documento (id) ON DELETE CASCADE,
    percentagem_similaridade NUMERIC(5, 2) NOT NULL DEFAULT 0,
    estado                   VARCHAR(20)   NOT NULL DEFAULT 'CONCLUIDO',
    documentos_comparados    INTEGER       NOT NULL DEFAULT 0,
    mensagem                 VARCHAR(500),
    data_geracao             TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_plagio_estado CHECK (estado IN ('CONCLUIDO', 'SEM_CORPUS', 'FALHOU')),
    CONSTRAINT ck_plagio_percentagem CHECK (percentagem_similaridade BETWEEN 0 AND 100)
);

CREATE TABLE plagio_correspondencia (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relatorio_id             BIGINT        NOT NULL REFERENCES relatorio_plagio (id) ON DELETE CASCADE,
    versao_semelhante_id     BIGINT        NOT NULL REFERENCES versao_documento (id) ON DELETE CASCADE,
    percentagem_similaridade NUMERIC(5, 2) NOT NULL,
    descricao                VARCHAR(300)  NOT NULL
);
CREATE INDEX ix_plagio_correspondencia ON plagio_correspondencia (relatorio_id);

-- ---------------------------------------------------------------------
-- Chat privado estudante <-> supervisor (RF07)
-- ---------------------------------------------------------------------
CREATE TABLE mensagem (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tcc_id        BIGINT       NOT NULL REFERENCES tcc (id) ON DELETE CASCADE,
    remetente_id  BIGINT       NOT NULL REFERENCES utilizador (id),
    conteudo      VARCHAR(4000) NOT NULL,
    anexo_nome    VARCHAR(255),
    anexo_caminho VARCHAR(500),
    anexo_tamanho BIGINT,
    enviada_em    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    lida_em       TIMESTAMPTZ
);
CREATE INDEX ix_mensagem_tcc ON mensagem (tcc_id, enviada_em);

-- ---------------------------------------------------------------------
-- Notificacoes in-app (RF09)
-- ---------------------------------------------------------------------
CREATE TABLE notificacao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario_id BIGINT       NOT NULL REFERENCES utilizador (id) ON DELETE CASCADE,
    tipo            VARCHAR(40)  NOT NULL,
    titulo          VARCHAR(200) NOT NULL,
    conteudo        VARCHAR(1000) NOT NULL,
    ligacao         VARCHAR(300),
    lida            BOOLEAN      NOT NULL DEFAULT FALSE,
    criada_em       TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_notificacao_destinatario ON notificacao (destinatario_id, lida, criada_em DESC);

-- ---------------------------------------------------------------------
-- Marcos / prazos definidos pelo Coordenador (RF10)
-- Modelo por curso + ano lectivo; ao arrancar um TCC as datas sao
-- copiadas para as fases, podendo depois ser ajustadas caso a caso.
-- ---------------------------------------------------------------------
CREATE TABLE milestone (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso          VARCHAR(120) NOT NULL,
    ano_lectivo    INTEGER      NOT NULL,
    numero_fase    INTEGER      NOT NULL,
    nome           VARCHAR(120) NOT NULL,
    data_inicio    DATE         NOT NULL,
    data_limite    DATE         NOT NULL,
    criado_por     BIGINT       REFERENCES utilizador (id),
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actualizado_em TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_milestone_fase   CHECK (numero_fase BETWEEN 1 AND 5),
    CONSTRAINT ck_milestone_datas  CHECK (data_limite >= data_inicio),
    CONSTRAINT ux_milestone UNIQUE (curso, ano_lectivo, numero_fase)
);

-- ---------------------------------------------------------------------
-- Registo de auditoria (RNF04)
-- ---------------------------------------------------------------------
CREATE TABLE auditoria (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilizador_id BIGINT       REFERENCES utilizador (id) ON DELETE SET NULL,
    actor         VARCHAR(150) NOT NULL,
    accao         VARCHAR(80)  NOT NULL,
    entidade      VARCHAR(80)  NOT NULL,
    entidade_id   BIGINT,
    detalhes      VARCHAR(2000),
    endereco_ip   VARCHAR(60),
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_auditoria_criado ON auditoria (criado_em DESC);
CREATE INDEX ix_auditoria_entidade ON auditoria (entidade, entidade_id);

-- ---------------------------------------------------------------------
-- Refresh tokens (RF02)
-- ---------------------------------------------------------------------
CREATE TABLE refresh_token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilizador_id BIGINT      NOT NULL REFERENCES utilizador (id) ON DELETE CASCADE,
    token_hash    VARCHAR(64) NOT NULL UNIQUE,
    expira_em     TIMESTAMPTZ NOT NULL,
    revogado      BOOLEAN     NOT NULL DEFAULT FALSE,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_refresh_utilizador ON refresh_token (utilizador_id);
